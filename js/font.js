const FONT_H = 10;
const glyphCache = new Map();

function glyphWidth(ch) {
  const g = GLYPHS[ch] || GLYPHS['?'];
  return g.reduce((m, r) => Math.max(m, r.length), 0);
}

function textWidth(str) {
  let w = 0;
  for (const ch of str) w += glyphWidth(ch) + 1;
  return Math.max(0, w - 1);
}

function glyphCanvas(ch, color) {
  const key = ch + color;
  let cv = glyphCache.get(key);
  if (cv) return cv;
  const g = GLYPHS[ch] || GLYPHS['?'];
  const p = new Pix(glyphWidth(ch), FONT_H);
  g.forEach((row, y) => [...row].forEach((c, x) => { if (c === '#') p.set(x, y, color); }));
  cv = p.canvas();
  glyphCache.set(key, cv);
  return cv;
}

// GBA text: dark letters with a soft shadow down and to the right
const TEXT_DARK = '#505058';
const TEXT_SHADOW = '#d0d0c8';

function drawText(ctx, str, x, y, color = TEXT_DARK, shadow = TEXT_SHADOW) {
  let cx = Math.round(x);
  y = Math.round(y);
  for (const ch of str) {
    if (shadow) {
      const s = glyphCanvas(ch, shadow);
      ctx.drawImage(s, cx + 1, y);
      ctx.drawImage(s, cx, y + 1);
      ctx.drawImage(s, cx + 1, y + 1);
    }
    ctx.drawImage(glyphCanvas(ch, color), cx, y);
    cx += glyphWidth(ch) + 1;
  }
  return cx;
}

// split text into lines that fit `maxW` pixels
function wrapText(str, maxW) {
  const out = [];
  for (const para of str.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const test = line ? line + ' ' + word : word;
      if (textWidth(test) <= maxW || !line) line = test;
      else { out.push(line); line = word; }
    }
    out.push(line);
  }
  return out;
}
